#!/usr/bin/env python3
"""Generate:
- public/api/index.html  (raw index for direct /api/ links)
- reference/crate-api.md  (vitepress page listing crate rustdocs)"""
import pathlib, sys

api = pathlib.Path(sys.argv[1]).parent
crates = sorted(d.name for d in api.iterdir()
                if d.is_dir() and d.name.startswith("bupha"))
links = "\n".join(
    f'  <li><a href="{c}/index.html">{c.replace("_", "-")}</a></li>'
    for c in crates)
api.joinpath("index.html").write_text(
    "<!doctype html><meta charset=utf-8>"
    "<title>bupha — Crate API</title>"
    "<style>body{background:#1b1b1f;color:#ddd;font-family:"
    "ui-monospace,monospace;max-width:640px;margin:4em auto;"
    "padding:0 1em}a{color:#a8b1ff;text-decoration:none}"
    "a:hover{text-decoration:underline}li{line-height:1.9}"
    "h1{font-size:1.3em}</style>"
    "<h1>bupha — Crate API</h1>\n<ul>\n" + links + "\n</ul>\n")

md = ["# Crate API", "",
      "<!-- generated by gen-api-index.py — links to rustdoc -->",
      "",
      "Crate-level docs generated by `cargo doc --workspace --no-deps`",
      "(`bun run docs:api`). Each link opens the crate's rustdoc.",
      ""]
for c in crates:
    name = c.replace('_', '-')
    md.append(
        f'- <a href="/bupha/api/{c}/index.html" '
        f'target="_blank"><code>{name}</code></a>')
pathlib.Path(__file__).parent.joinpath(
    "reference/crate-api.md").write_text("\n".join(md) + "\n")
print(f"api index + rust-api.md: {len(crates)} crates")
