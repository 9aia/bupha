#!/usr/bin/env python3
"""Generate public/api/index.html — the styled index served at
/bupha/api/. (reference/crate-api.md is generated by
gen-crate-map.py — do not write it here.)"""
import pathlib, sys

api = (pathlib.Path(sys.argv[1]) if len(sys.argv) > 1
       else pathlib.Path("public/api"))
if api.is_file():
    api = api.parent
crates = sorted(d.name for d in api.iterdir()
                if d.is_dir() and d.name.startswith("bupha"))
links = "\n".join(
    f'  <li><a href="{c}/index.html">{c.replace("_", "-")}</a></li>'
    for c in crates)
api.joinpath("index.html").write_text(
    "<!doctype html><meta charset=utf-8>"
    "<title>bupha — Crate API</title>"
    "<style>body{background:#1b1b1f;color:#ddd;font-family:"
    "ui-monospace,monospace;max-width:640px;margin:4em auto;"
    "padding:0 1em}a{color:#a8b1ff;text-decoration:none}"
    "a:hover{text-decoration:underline}li{line-height:1.9}"
    "h1{font-size:1.3em}</style>"
    "<h1>bupha — Crate API</h1>\n<ul>\n" + links + "\n</ul>\n")

print(f"api index: {len(crates)} crates")
