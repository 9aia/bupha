#!/usr/bin/env python3
"""Generate docs/reference/config.md from config-struct doc comments
— the structs across core + impl crates are the source of truth."""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).parent / ".."
OUT  = pathlib.Path(__file__).parent / "reference" / "config.md"

# file → {struct: section title}; order preserved
SRCS = {
    "crates/bupha-core/src/lib.rs": {
        "Config": "Top level", "RepoEntry": "`[[repo]]`",
        "TriggerCfg": "`[trigger]`", "RunnerCfg": "`[runner]`",
        "StatusCfg": "`[status]`", "TunnelCfg": "`[tunnel]`",
        "CacheCfg": "`[cache]`", "WorktreeCfg": "`[worktree]`",
    },
    "crates/bupha-dagger/src/lib.rs": {"DaggerCfg": "`[runner]` — kind `dagger`"},
    "crates/bupha-shell/src/lib.rs":  {"ShellCfg": "`[runner]` — kind `shell`"},
    "crates/bupha-ssh/src/lib.rs":    {"SshCfg": "`[runner]` — kind `ssh`"},
}
SRC = {n: (ROOT / f).read_text()
       for f, names in SRCS.items() for n in names}
TITLES = {n: t for names in SRCS.values() for n, t in names.items()}
STRUCTS = [n for names in SRCS.values() for n in names]

SIMPLE = {"String": "string", "PathBuf": "path", "bool": "bool",
          "u16": "int", "usize": "int", "Vec<String>": "list",
          "QueuePolicy": '"latest" | "all"'}

def fields(name):
    m = re.search(rf"pub struct {name} \{{(.*?)\n\}}", SRC[name], re.S)
    if not m: return []
    rows = []
    for fm in re.finditer(
            r"((?:\s*(?:///|#\[)[^\n]*\n)+)\s*"
            r"pub (\w+): ([^,\n]+),?", m.group(1)):
        prelude = fm.group(1)
        doc = " ".join(l.split("///", 1)[1].strip()
                       for l in prelude.splitlines() if "///" in l)
        fname, ty = fm.group(2), fm.group(3).strip()
        opt = (ty.startswith("Option")
               or "serde(default" in prelude)
        inner = ty[7:-1] if ty.startswith("Option") else ty
        rows.append((fname, SIMPLE.get(inner, inner),
                     "" if opt else "required", doc or "—"))
    return rows

out = ["# Config — `bupha.toml`",
       "<!-- generated by gen-config-docs.py — edit the struct doc comments,",
       "     not this file -->", ""]
for name in STRUCTS:
    out += [f"## {TITLES[name]}", "",
            "| field | type | required | notes |",
            "|---|---|---|---|"]
    for fname, ty, req, doc in fields(name):
        doc = (doc.replace("|", "\\|")
                  .replace("<", "&lt;").replace(">", "&gt;"))
        out.append(
            f"| `{fname}` | `{ty}` | {req or 'optional'} | {doc} |")
    out.append("")
out += [
    "## Constraints", "",
    "- `queue = \"all\"` rejects `cancel_running = true` at load —",
    "  killing a run would silently drop a promised commit.",
    "- `runner.kind` and `trigger.kind`/`status.kind` resolve to impl",
    "  crates; unknown kinds fail at `bupha doctor`/startup.",
    "- `deny_unknown_fields`: typos in field names fail the load.",
    ""]
OUT.write_text("\n".join(out))
print(f"wrote {OUT}")
