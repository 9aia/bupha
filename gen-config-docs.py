#!/usr/bin/env python3
"""Generate docs/reference/config.md from bupha-core config struct
doc comments — the structs are the source of truth."""
import pathlib, re, sys

CORE = pathlib.Path(__file__).parent / ".." / "crates/bupha-core/src/lib.rs"
OUT  = pathlib.Path(__file__).parent / "reference" / "config.md"
STRUCTS = ["Config", "RepoEntry", "TriggerCfg", "RunnerCfg",
           "StatusCfg", "TunnelCfg", "WorktreeCfg"]
TITLES = {
    "Config": "Top level", "RepoEntry": "`[[repos]]`",
    "TriggerCfg": "`[trigger]`", "RunnerCfg": "`[runner]`",
    "StatusCfg": "`[status]`", "TunnelCfg": "`[tunnel]`",
    "WorktreeCfg": "`[worktree]`",
}
SIMPLE = {"String": "string", "PathBuf": "path", "bool": "bool",
          "u16": "int", "usize": "int", "Vec<String>": "list",
          "QueuePolicy": '"latest" | "all"'}

src = CORE.read_text()
def fields(name):
    m = re.search(rf"pub struct {name} \{{(.*?)\n\}}", src, re.S)
    rows = []
    for fm in re.finditer(
            r"((?:\s*(?:///|#\[)[^\n]*\n)+)\s*"
            r"pub (\w+): ([^,\n]+),?", m.group(1)):
        prelude = fm.group(1)
        doc = " ".join(l.split("///", 1)[1].strip()
                       for l in prelude.splitlines() if "///" in l)
        fname, ty = fm.group(2), fm.group(3).strip()
        opt = (ty.startswith("Option")
               or "serde(default" in prelude)
        inner = ty[7:-1] if ty.startswith("Option") else ty
        rows.append((fname, SIMPLE.get(inner, inner),
                     "" if opt else "required", doc or "—"))
    return rows

out = ["# Config reference",
       "",
       "<!-- generated by gen-config-docs.py from bupha-core struct",
       "doc comments — edit the comments, not this file -->",
       "",
       "`bupha.toml`. Secrets are never values here — only env-var",
       "*names* (`secret_env`, `token_env`, `sccache_conf`).",
       ""]
for name in STRUCTS:
    out += [f"## {TITLES[name]}", "",
            "| field | type | required | notes |",
            "|---|---|---|---|"]
    for fname, ty, req, doc in fields(name):
        doc = doc.replace("|", "\\|")
        out.append(
            f"| `{fname}` | `{ty}` | {req or 'optional'} | {doc} |")
    out.append("")
out += [
    "## Constraints", "",
    "- `queue = \"all\"` rejects `cancel_running = true` at load —",
    "  killing a run would silently drop a promised commit.",
    "- `runner.kind` and `trigger.kind`/`status.kind` resolve to impl",
    "  crates; unknown kinds fail at `bupha doctor`/startup.",
    "- `deny_unknown_fields`: typos in field names fail the load.",
    ""]
OUT.write_text("\n".join(out))
print(f"wrote {OUT}")
